-- =====================================================================
-- Embedded (Apache Derby) schema used by the automated JUnit tests and
-- the headless end-to-end demo so they can run WITHOUT a MySQL server.
-- Table and column names match sql/schema.sql exactly; only the
-- dialect-specific DDL differs (IDENTITY instead of AUTO_INCREMENT).
-- The application DAOs use the same portable SQL against both engines.
-- =====================================================================

CREATE TABLE users (
    id            BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    role          VARCHAR(24)  NOT NULL,
    active        SMALLINT     NOT NULL DEFAULT 1,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE user_public_keys (
    id            BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT NOT NULL,
    algorithm     VARCHAR(64)  NOT NULL DEFAULT 'RSA',
    key_size_bits INT          NOT NULL DEFAULT 2048,
    public_key    VARCHAR(3000) FOR BIT DATA NOT NULL,
    key_version   INT          NOT NULL DEFAULT 1,
    keystore_ref  VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_upk_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_upk_user_version UNIQUE (user_id, key_version)
);

CREATE TABLE image_transfers (
    id                BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    transfer_id       VARCHAR(36)  NOT NULL,
    sender_id         BIGINT NOT NULL,
    recipient_id      BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type      VARCHAR(64),
    plaintext_size    BIGINT NOT NULL,
    ciphertext_size   BIGINT NOT NULL,
    plaintext_sha256  VARCHAR(64)  NOT NULL,
    algorithm         VARCHAR(64)  NOT NULL,
    key_size_bits     INT          NOT NULL DEFAULT 256,
    nonce             VARCHAR(16) FOR BIT DATA NOT NULL,
    tag_bits          INT          NOT NULL DEFAULT 128,
    status            VARCHAR(24)  NOT NULL,
    storage_ref       VARCHAR(512),
    error_detail      VARCHAR(255),
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    received_at       TIMESTAMP,
    completed_at      TIMESTAMP,
    CONSTRAINT uk_transfers_uuid UNIQUE (transfer_id),
    CONSTRAINT fk_transfers_sender FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT fk_transfers_recipient FOREIGN KEY (recipient_id) REFERENCES users (id)
);

CREATE TABLE protected_key_material (
    id               BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    transfer_id      VARCHAR(36)  NOT NULL,
    wrap_algorithm   VARCHAR(80)  NOT NULL DEFAULT 'RSA/ECB/OAEPWithSHA-256AndMGF1Padding',
    wrapped_key      VARCHAR(1024) FOR BIT DATA NOT NULL,
    recipient_key_id BIGINT,
    key_version      INT          NOT NULL DEFAULT 1,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_pkm_transfer UNIQUE (transfer_id),
    CONSTRAINT fk_pkm_transfer FOREIGN KEY (transfer_id)
        REFERENCES image_transfers (transfer_id) ON DELETE CASCADE,
    CONSTRAINT fk_pkm_recip_key FOREIGN KEY (recipient_key_id)
        REFERENCES user_public_keys (id) ON DELETE SET NULL
);

CREATE TABLE audit_logs (
    id          BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_type  VARCHAR(48)  NOT NULL,
    username    VARCHAR(64),
    user_id     BIGINT,
    transfer_id VARCHAR(36),
    outcome     VARCHAR(16)  NOT NULL,
    detail      VARCHAR(255),
    source_ip   VARCHAR(45),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_role ON users (role);
CREATE INDEX idx_transfers_recipient ON image_transfers (recipient_id, status);
CREATE INDEX idx_transfers_sender ON image_transfers (sender_id, status);
CREATE INDEX idx_transfers_status ON image_transfers (status);
CREATE INDEX idx_audit_event ON audit_logs (event_type);
CREATE INDEX idx_audit_user ON audit_logs (username);
CREATE INDEX idx_audit_transfer ON audit_logs (transfer_id);
CREATE INDEX idx_audit_created ON audit_logs (created_at);
